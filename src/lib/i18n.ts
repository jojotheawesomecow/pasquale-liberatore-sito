/** Sceglie il campo nella lingua richiesta, con ritorno all'italiano se il campo inglese è vuoto. */
export function campo<T extends Record<string, unknown>>(obj: T, chiave: string, lang: Lang): string {
  const en = lang === "en" ? (obj[`${chiave}_en`] as string | undefined) : undefined;
  const it = obj[chiave] as string | undefined;
  return (en && en.trim()) || it || "";
}
